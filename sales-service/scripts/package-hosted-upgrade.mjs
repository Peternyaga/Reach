import {cp, mkdir, rm, stat} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publish = path.join(root, 'publish');
const release = path.join(publish, 'reach');
const staging = path.join(publish, 'upgrade-stage');
const archive = path.join(publish, 'fieldwork-reach-upgrade.zip');
await stat(path.join(release, 'public_html', 'index.html'));
await stat(path.join(release, 'fieldwork', 'backend', 'migrate.php'));
if (path.dirname(staging) !== publish || path.basename(staging) !== 'upgrade-stage') throw new Error('Unsafe upgrade staging path');
await rm(staging, {recursive: true, force: true});
await rm(archive, {force: true});
await mkdir(staging, {recursive: true});
await cp(path.join(release, 'public_html'), path.join(staging, 'public_html'), {recursive: true});
await cp(path.join(release, 'fieldwork'), path.join(staging, 'fieldwork'), {recursive: true});
await cp(path.join(root, 'deploy', 'backup-database.php'), path.join(staging, 'backup-database.php'));
await cp(path.join(root, 'deploy', 'install-upgrade.sh'), path.join(staging, 'install-upgrade.sh'));
await cp(path.join(root, 'deploy', 'UPGRADE.txt'), path.join(staging, 'UPGRADE.txt'));
await cp(path.join(root, 'deploy', 'PROJECTS-2026-10-14.md'), path.join(staging, 'PROJECTS-2026-10-14.md'));
await cp(path.join(root, 'deploy', 'SIGNUP-2026-10-14.md'), path.join(staging, 'SIGNUP-2026-10-14.md'));
await cp(path.join(root,'deploy','CONTACTS-2026-10-19.md'),path.join(staging,'CONTACTS-2026-10-19.md'));
await cp(path.join(root,'deploy','SCHEDULING-2026-10-20.md'),path.join(staging,'SCHEDULING-2026-10-20.md'));
await cp(path.join(root,'deploy','TEAM-ACCESS-2026-10-16.md'),path.join(staging,'TEAM-ACCESS-2026-10-16.md'));
await cp(path.join(root, 'deploy', 'RESEARCH-2026-10-15.md'), path.join(staging, 'RESEARCH-2026-10-15.md'));
await cp(path.join(root, 'PROJECT-ORGANIZATION.md'), path.join(staging, 'PROJECT-ORGANIZATION.md'));
execFileSync('tar', ['-a', '-cf', archive, '-C', staging, '.'], {stdio: 'inherit'});
console.log(`Uploadable upgrade package: ${archive}`);
